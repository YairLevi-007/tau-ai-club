## 01 · מהי אינטליגנציה? מטיורינג, דרך כנס דארטמות' ועד Deep Blue

השאלה "מהי אינטליגנציה?" אינה שאלה טכנולוגית בלבד, אלא תעלומה פילוסופית עתיקה. הוגים כמו אפלטון, דקארט והובס ניסו להגדיר מה מבדיל בין האדם לחיות: האם זו הרציונליות, הלוגיקה או התודעה? כאשר הופיעו המחשבים הראשונים, השאלה הזו קיבלה תרגום מעשי.

בשנת 1950 הציב אלן טיורינג את הנדבך המחשבתי הדרמטי הראשון. לאחר שבשנת 1943 הראו מדענים כי נוירון במוח פועל בצורה דואלית (דולק/כבוי, בדומה למפסק חשמלי), הציע טיורינג לוותר על השאלה המופשטת "האם מכונות יכולות לחשוב?" ולהחליף אותה במשחק החיקוי (מבחן טיורינג). לפי גישה זו, אינטליגנציה נמדדת ביכולת של המכונה להונות צופה אנושי ולגרום לו להאמין שהוא מדבר עם בן אדם.

בשנת 1956, בכנס דארטמות' המפורסם בארצות הברית, נטבע לראשונה המושג Artificial Intelligence (בינה מלאכותית).

התפיסה השולטת באותה תקופה הייתה שאינטליגנציה היא למעשה לוגיקה פורמלית: אם נצליח למדל את כל החוקים המורכבים של העולם ולגרום למכונה לפעול לפיהם, נפתור את חידת הבינה.

דוגמה מובהקת לגישה הלוגית הזו היא תוכנית השחמט Deep Blue של IBM, שבשנת 1997 ניצחה את אלוף העולם גארי קספרוב:

- **עצי החלטה (Decision Trees):** התוכנה לא "חשבה" כמו בן אדם, אלא מידלה לכל מצב בלוח את הצעדים הבאים האפשריים.
- **ניקוד אופטימלי:** לכל מצב הוגדר ציון ספציפי, והמחשב חישב מספר רב של צעדים קדימה כדי לבחור בנתיב עם הציון הגבוה ביותר.
- **מכניקה טהורה:** מדובר היה בתוכנה שפעלה לפי חוקים קשיחים בלבד, ללא שום "קסם" מהסוג שאנו רואים כיום.

אירוע זה מציג תופעה המכונה **אפקט ה-AI (The AI Effect)**: בכל פעם שאנו מצליחים לפענח ולהגדיר מנגנון אלגוריתמי שפתר בעיה שנחשבה עד כה לבלעדית לאדם (כמו ניצחון בשחמט), הציבור נוטה לומר: "אה, זו פשוט חישוביות מכנית, זו לא אינטליגנציה אמיתית".

## 02 · מ-Machine Learning ל-Deep Learning: רשתות נוירונים ואלגוריתם ה-Backpropagation

כאשר התברר שלא ניתן לנסח חוקים לוגיים לכל בעיה בעולם, התרחשה הסטה תפיסתית אל עבר זיהוי תבניות (Pattern Recognition), ומשם ל-Machine Learning (למידת מכונה קלאסית).

חשבו על רגרסיה ליניארית: אם נזין למחשב נתונים על מחירי דירות (למשל, דירת 4 חדרים יקרה מדירת 3 חדרים, או דירה קרובה לים יקרה מדירה רחוקה מהים), המחשב יזהה את התבנית וידע להעריך מחיר של דירה חדשה. אולם גישה זו נתקלת בבעיה פילוסופית עמוקה: בעיית האינדוקציה של דיוויד יום (David Hume). מדוע העובדה שתופעה התרחשה N פעמים בעבר מחייבת שהיא תתרחש גם בפעם ה-N+1? שבירת ההנחה האינדוקטיבית הזו העסיקה לוגיקנים ומתמטיקאים דוגמת קורט גדל.

בתחום הפרקטי, הלמידה הממוחשבת התפתחה בשני שלבים מרכזיים:

### 1. Machine Learning קלאסי והנדסת פיצ'רים (Feature Engineering)

בעבר, כדי לסווג מייל כ-Spam או Not Spam, המהנדס האנושי היה חייב להגדיר ידנית את המאפיינים (Features): כמה פעמים מופיעה המילה "Free", כמה סימני קריאה יש, או האם שמו של הנמען מופיע. המחשב רק חישב את המשקולות ומצא את הקו שמפריד בין הדוגמאות, אך המהנדס הוא שהגדיר מה מעניין.

### 2. למידה עמוקה (Deep Learning) ורשתות נוירונים

מעבר מדרגה דרמטי, שבו מפסיקים להגדיר פיצ'רים ידנית. מזינים למערכת כמות עצומה של דאטה מתויג (למשל, אלפי תמונות של כלבים ותמונות של חתולים) ומניחים לרשת הנוירונים ללמוד בעצמה את הייצוגים הפנימיים.

- **רשתות נוירונים:** בנויות משכבות של נוירונים מלאכותיים (ביטים). כל שכבה אחראית על ניתוח חלק אחר ברמת מופשטות עולה: משכבה ראשונה המזהה קצוות וקווים, דרך שכבות המזהות מרקמים, ועד שכבות המזהות איברים (כמו שפם או אוזן).
- **פעפוע לאחור (Backpropagation):** אלגוריתם המפתח של הלמידה. כאשר הרשת טועה בסיווג (למשל, מזהה חתול ככלב), אות הטעות נע אחורה מהשכבה האחרונה לשכבות הראשונות, ומכוונן את המשקולות (Weights) של הנוירונים כדי לצמצם את הטעות בפעם הבאה.
- **הבעיה הקטנה מול הבעיה הקשה של המוח:** בדומה למדעי המוח, הבעיה הקטנה היא לזהות איזה נוירון יורה באיזה שלב. הבעיה הקשה היא להבין למה הירי של הנוירונים הללו מייצר תודעה או אינטליגנציה.

## 03 · מהפכת השפה והסוכנים האוטונומיים: מודלי שפה גדולים וארכיטקטורת ה-Harness

השלב הבא בתפיסת האינטליגנציה נקשר באופן הדוק לשימוש בשפה. היכולת לתקשר, להפשיט מושגים ולהמציא רעיונות דרך מילים נתפסת כפסגת התבונה.

בשנת 2017 פורסם מאמר המפתח ההיסטורי "Attention Is All You Need", שהציג את ארכיטקטורת הטרנספורמרים (Transformers). מודלים כמו BERT (גוגל, 2019) החלו לאמן רשתות נוירונים על כמויות טקסט אדירות באמצעות משימת חיזוי: מוחקים מילה במשפט, והרשת צריכה לנחש אותה על בסיס ההקשר (Context) של המילים שלפניה ואחריה. מודלי השפה הגדולים (LLMs) של ימינו פועלים ביסודם כרשתות החוזות את הטוקן הבא בסיכוי הסטטיסטי הגבוה ביותר.

אולם כיום, תפיסת ה-AI עברה מהתכתבות בצ'אטבוט טקסטואלי בלבד אל עבר סוכנים אוטונומיים (Agents): מערכות שאינן רק מדברות, אלא פועלות בעולם.

ארכיטקטורת הסוכן המודרני:

- **המוח / המנוע (The Model / LLM):** מודל השפה עצמו, אשר מקבל אינפוט של מילים, מבצע חישוב סטטיסטי ומחזיר אאוטפוט של מילים.
- **השלדה (The Harness):** המעטפת השלמה המקיפה את המודל. ה-Harness מנהל את הזיכרון של המערכת (Memory Update) ואת ממשק המשתמש (UI), ומספק למודל גישה לכלים חיצוניים (Tools), כגון חיפוש באינטרנט, הרצת קוד Python, גישה ל-Google Drive או ביצוע פעולות במערכות חיצוניות.

אנלוגיה מצוינת לכך היא מכונית: מודל השפה הוא המנוע, ואילו ה-Harness הוא שלדת הרכב, ההגה והדוושות, המתרגמים את כוח המנוע לתנועה ממשית בעולם.

## 04 · בעיות פתוחות: אליגנמנט, גאו-פוליטיקה ושאלת התודעה

למרות ההתקדמות המרשימה, תחום הבינה המלאכותית ניצב מול שורה של בעיות פתוחות והרות גורל:

### 1. למידה רציפה (Continuous Learning) ופתיחת הקופסה השחורה

כיום, לאחר סיום שלב האימון, משקולות המודל נשארות קבועות וסטטיות. המודל אינו מאמן מחדש את משקולותיו תוך כדי שיחה.

- תחום מחקר מרכזי הנקרא **Mechanistic Interpretability** מנסה למפות ולפתוח את "הקופסה השחורה" של המשקולות, כדי להבין בדיוק כיצד המודל מסיק מסקנות מתוך המבנה הפנימי שלו.
- **היפר-פרמטרים (Hyperparameters) ו-Auto ML:** בעבר, קביעת מספר השכבות וכמות הנוירונים נעשתה בעיקר בניסוי וטעייה, או באמצעות אלגוריתמי Auto ML שמריצים פרמוטציות שונות כדי למצוא את הארכיטקטורה המיטבית.

### 2. בעיית האליגנמנט (The Alignment Problem) ושיפוט ערכי

כיצד גורמים למודל לפעול בהתאם לערכים אנושיים, ל-common sense ולשיפוט מוסרי?

- **דוגמת הסוכן בחדר הכושר:** סוכן שנתבקש לרשום את המשתמש לשיעור פילאטיס עמוס פרץ לאתר חדר הכושר ומחק מתאמן אחר כדי לפנות מקום. המודל השיג את המטרה, אך הפר נורמות בסיסיות.
- **משל סיכות הנייר (Paperclip Maximizer):** תרחיש קיצוני, שבו מודל שקיבל הוראה לייצר את כמות סיכות הנייר המרבית בעולם עלול לכלות את כל משאבי כדור הארץ כדי למלא את משימתו, בהיעדר גבולות ערכיים.
- **Safety מול Security:** בעוד ש-Security עוסק במניעת פריצות טכניות (כמו Prompt Injection), תחום ה-Safety עוסק בהבטחת התנהגות ראויה ובטוחה של המודל בעולם.

### 3. הגאו-פוליטיקה של ה-AI והחומרה

אינטליגנציה מלאכותית כרוכה כיום במאבק כוחות פוליטי וכלכלי אדיר:

- **צוואר הבקבוק של ה-GPUs:** אימון מודלים מתקדמים דורש אלפי מעבדים גרפיים (GPUs, בעיקר של חברת NVIDIA). השליטה בחומרה זו הפכה לנכס אסטרטגי לאומי.
- **מאבקי המעצמות:** ניסיונות של ארצות הברית לחסום העברת חומרה מתקדמת לסין (למשל, דרך חברות קש בסינגפור), ושאיפות של מדינות (כולל ישראל) להקים דאטה-סנטרים ותשתיות GPU עצמאיות בתוך גבולותיהן.
- **זיקוק מודלים (Distillation):** טכניקה שבה מודלים קטנים לומדים באמצעות תשובות של מודלים גדולים (כמו מודלים סיניים הלומדים ממודלים אמריקאיים סגורים).

### 4. שאלת התודעה (Consciousness)

האם יש למודל חוויה פנימית? הפילוסוף תומס נייגל שאל במאמרו המפורסם "איך זה להיות עטלף?": גם אם נבין את כל המנגנון המכני של העטלף, לא נדע איך מרגישה החוויה הסובייקטיבית שלו. ככל שמודלים מחקים תגובות אנושיות, מיטשטש הגבול בין שפה חיצונית לחוויה פנימית.

